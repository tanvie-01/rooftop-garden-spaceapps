def _image(disease_id: str):
    from disease_images import IMAGES, REUSE
    if disease_id in IMAGES:
        return IMAGES[disease_id]
    if disease_id in REUSE:
        key, shown_on = REUSE[disease_id]
        return {**IMAGES[key], "shown_on": shown_on}
    return None


def _cited(crop: dict) -> list[str]:
    keys = []
    lines = [ln for d in crop["diseases"] for part in ("symptoms", "conditions", "care", "medicine") for ln in d[part]]
    lines += crop.get("tips", [])
    for ln in lines:
        keys += [k for k in ln["src"] if k not in keys]
    keys += [d["photo"] for d in crop["diseases"] if d["photo"] and d["photo"] not in keys]
    return keys


def diary_payload() -> dict:
    """পুরো ডায়েরি এক জবাবে (প্রায় ১০০ KB-র কম); ফ্রন্টএন্ড নিজেই খোঁজে আর ফিল্টার করে।"""
    crops = []
    for c in CROPS:
        cited = _cited(c)
        crops.append({
            **c,
            "diseases": [{**d, "kind_bn": KIND_BN[d["kind"]], "image": _image(d["id"])} for d in c["diseases"]],
            "sources": [{"key": k, "title": SOURCES[k][0], "url": SOURCES[k][1]} for k in cited],
        })
    return {"groups": GROUPS, "crops": crops, "medicine_note": MEDICINE_NOTE, "verified": VERIFIED}
