def ph_label(ph: float) -> str:
    return next(label for limit, label in PH_SCALE_BN if ph < limit)


def good_crops(soil_type: str) -> list[dict]:
    """ফসল সাজেশনের একই তালিকা (crops.py) থেকে, যেন দুই জায়গায় দুরকম কথা না হয়।"""
    return [
        {"name": c["name"], "name_bn": c["bn"], "category": c["cat"], "min_pot": c["min_pot"], "min_sun": c["min_sun"]}
        for c in CROPS if soil_type in c["soils"]
    ]


def soil_report(soil_type: str) -> dict:
    info = SOIL_INFO[soil_type]
    low, high = info["ph_range"]
    return {
        "soil_type": soil_type,
        **info,
        "ph_range_label": f"{ph_label(low)} থেকে {ph_label(high - 0.01)}",
        "ideal_ph": list(IDEAL_PH),
        "good_crops": good_crops(soil_type),
        "disclaimer": DISCLAIMER,
        "verified": VERIFIED,
    }


def soil_report_text(soil_type: str, method_bn: str, texture_bn: str | None, is_mock: bool, when: str) -> str:
    """চ্যাটবটের প্রসঙ্গের জন্য ছোট লেখা।"""
    r = soil_report(soil_type)
    crops = ", ".join(c["name_bn"] for c in r["good_crops"][:8])
    return (
        f"ব্যবহারকারীর শেষ মাটির রিপোর্ট ({when}, {method_bn}): {r['name_bn']} ({soil_type})"
        + (f", শ্রেণি {texture_bn}" if texture_bn else "")
        + (" — নমুনা মডেলের ফল, আসল নয়" if is_mock else "")
        + "\n- বৈশিষ্ট্য: " + "; ".join(f"{k}: {v}" for k, v in r["traits"])
        + f"\n- সাধারণ pH: {r['ph_range'][0]}–{r['ph_range'][1]} ({r['ph_range_label']}); এটা মাপা মান নয়"
        + f"\n- এই মাটিতে ভালো হয়: {crops}"
    )
