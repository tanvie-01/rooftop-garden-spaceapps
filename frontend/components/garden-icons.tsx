export type GIconName = keyof typeof ICONS;

export function GIcon({ name, className = "h-5 w-5", title }: { name: GIconName; className?: string; title?: string }) {
  const d: Def = ICONS[name];
  const body = (
    <>
      {d.soft?.map((p) => <path key={`s${p}`} d={p} fill="currentColor" fillOpacity={0.16} stroke="none" />)}
      {d.line.map((p) => <path key={p} d={p} />)}
      {d.dot?.map(([x, y]) => <circle key={`${x},${y}`} cx={x} cy={y} r={0.9} fill="currentColor" stroke="none" />)}
    </>
  );
  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.7}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={`inline-block shrink-0 align-[-0.2em] ${className}`}
      role={title ? "img" : undefined}
      aria-label={title}
      aria-hidden={title ? undefined : true}
    >
      {d.flip ? <g transform="matrix(1 0 0 -1 0 24)">{body}</g> : body}
    </svg>
  );
}

/** লেখার আগে ছোট icon, লেখার সাথে এক লাইনে (যেমন শিরোনাম, লেবেল)। */
export function IconText({ icon, children, className = "", iconClass = "h-[1.1em] w-[1.1em]" }: {
  icon: GIconName;
  children: React.ReactNode;
  className?: string;
  iconClass?: string;
}) {
  return (
    <span className={`inline-flex items-center gap-1.5 ${className}`}>
      <GIcon name={icon} className={iconClass} />
      <span>{children}</span>
    </span>
  );
}

const MARK: Record<string, GIconName> = { "✓": "tick", "✗": "x", "△": "warning" };

/** backend-এর কারণের লেখা "✓ ...", "✗ ...", "△ ..."-এর প্রথম চিহ্নের জায়গায় icon (রং আসে বাইরের text-রং থেকে)। */
export function ReasonText({ text }: { text: string }) {
  const icon = MARK[text[0]];
  if (!icon) return <>{text}</>;
  return (
    <span className="inline-flex items-start gap-1.5">
      <GIcon name={icon} className="mt-[0.15em] h-4 w-4" />
      <span>{text.slice(1).trim()}</span>
    </span>
  );
}
