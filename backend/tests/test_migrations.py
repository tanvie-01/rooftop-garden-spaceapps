"""Alembic মাইগ্রেশন আর models.py এক থাকে কিনা। models.py বদলে মাইগ্রেশন বানাতে ভুলে গেলে ফেল করবে:
    venv\\Scripts\\alembic revision --autogenerate -m "কী বদলালে"
"""
from pathlib import Path

from alembic import command
from alembic.config import Config
from sqlalchemy import text

import pytest

from database import IS_SQLITE, Base, engine


# PostgreSQL-এ টেস্ট চলে আলাদা schema-য় (conftest), সেখানে Alembic-এর তুলনা public দেখে ফেলে।
# models আর মাইগ্রেশনের মিল ডাটাবেস-নির্ভর নয়, তাই SQLite-এ যাচাই যথেষ্ট।
@pytest.mark.skipif(not IS_SQLITE, reason="drift check runs on SQLite; the PostgreSQL test schema confuses autogenerate")
def test_migrations_build_the_same_schema_as_models():
    Base.metadata.drop_all(bind=engine)
    cfg = Config(str(Path(__file__).resolve().parents[1] / "alembic.ini"))
    cfg.attributes["configure_logger"] = False
    try:
        command.upgrade(cfg, "head")
        command.check(cfg)  # পার্থক্য থাকলে AutogenerateDiffsDetected
    finally:
        with engine.begin() as conn:
            conn.execute(text("DROP TABLE IF EXISTS alembic_version"))
